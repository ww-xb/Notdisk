package com.notdisk.provider.p115.auth

import com.notdisk.core.model.AccountId

/**
 * The credential material for one 115 account.
 *
 * ### Why these four values and not "a token"
 * `API_REFERENCE.md` §2.1 Step 3 documents the single most consequential detail of this
 * integration: 115 does **not** deliver its session through `Set-Cookie`. The `UID` / `CID` /
 * `SEID` / `KID` values arrive inside the `login/qrcode` **response body** (`data.cookie`), and the
 * web front-end writes them into `document.cookie` itself. Any implementation that only reads
 * response headers — a HTTP client with a cookie jar, a naive proxy — silently ends up with no
 * usable session. So the client persists them explicitly.
 *
 * ### Security
 * This object is a credential. It must only ever live:
 *  - in memory for the duration of a session, and
 *  - in encrypted storage at rest ([P115CredentialStore]).
 *
 * It must never be logged, never be written to Room as a plain column, and never be included in a
 * `CloudAccount` (which is a *display* model). [toString] is overridden to make an accidental
 * interpolation into a log line harmless.
 */
data class P115Credential(
    /** `USERSESSIONID` — the primary 64-hex ticket (§2.1 Step 4). */
    val userSessionId: String,
    /** `UID` — `{user_id}_A1_{timestamp}`. */
    val uid: String,
    /** `CID` — 32-hex client identifier. */
    val cid: String,
    /** `SEID` — 120-hex long-lived session key. */
    val seid: String,
    /** `KID` — 32-hex key identifier. */
    val kid: String,
    /** `user_id` reported by the login response; used for display, not for authentication. */
    val userId: String,
    /**
     * `PHPSESSID`, when the server issued one.
     * Optional because it is a server-side session cookie rather than a documented credential and
     * has been observed to be absent on some responses.
     */
    val phpSessionId: String? = null,
    /** When this credential was obtained, epoch millis. Used for diagnostics and rotation hints. */
    val obtainedAt: Long,
) {
    /**
     * Renders the cookie header exactly as the vendor's own front-end would.
     *
     * The order is fixed (`USERSESSIONID` first, matching §1.4's example) so that captured requests
     * are byte-comparable during debugging, and `null`/blank members are omitted rather than sent
     * as empty values.
     */
    fun cookieHeader(): String = buildString {
        append("USERSESSIONID=").append(userSessionId)
        append("; UID=").append(uid)
        append("; CID=").append(cid)
        append("; SEID=").append(seid)
        append("; KID=").append(kid)
        if (!phpSessionId.isNullOrBlank()) append("; PHPSESSID=").append(phpSessionId)
    }

    /**
     * True when the credential is structurally usable.
     *
     * Deliberately checks presence, not validity: only the server can say whether a session is
     * still alive (`my.115.com/?ct=ajax&ac=nav`). A structurally-complete-but-expired credential is
     * exactly the case that must produce a `TokenExpired` from a *server* call rather than a local
     * "not logged in" guess.
     */
    val isComplete: Boolean
        get() = userSessionId.isNotBlank() &&
            uid.isNotBlank() &&
            cid.isNotBlank() &&
            seid.isNotBlank() &&
            kid.isNotBlank()

    /** Redacted by design: interpolating a credential into a string must never leak it. */
    override fun toString(): String =
        "P115Credential(userId=$userId, uid=${uid.take(6)}…, session=***, seid=***)"
}

/**
 * Encrypted-at-rest storage for [P115Credential]s, keyed by the *local* [AccountId].
 *
 * ### Why keyed by the local account id
 * The local id is generated by the app and survives a re-authorisation of the same vendor account.
 * Keying by `user_id` instead would lose every cached association when a user re-logs in, and would
 * make it impossible to bind two accounts that happen to share a vendor id (which is exactly what
 * happens with 115's `aid` vs. personal-space distinction in shared-folder scenarios).
 *
 * ### Implementation contract
 * Implementations must use Android's encrypted storage (see
 * `P115EncryptedCredentialStore`). A plain `SharedPreferences` or a Room column is **not**
 * acceptable: §6.3 of the brief forbids it, and a 120-hex `SEID` is a long-lived bearer secret.
 */
interface P115CredentialStore {

    suspend fun save(accountId: AccountId, credential: P115Credential)

    suspend fun load(accountId: AccountId): P115Credential?

    suspend fun delete(accountId: AccountId)

    /** Account ids with a stored credential. Never returns the credentials themselves. */
    suspend fun listAccountIds(): List<AccountId>
}

/**
 * In-memory store used by unit tests and by the JVM-side contract tests (where the Android Keystore
 * does not exist).
 *
 * It is intentionally *not* registered in the production dependency graph, so a mis-wired build
 * cannot silently fall back to unencrypted storage.
 */
class InMemoryP115CredentialStore(
    initial: Map<AccountId, P115Credential> = emptyMap(),
) : P115CredentialStore {

    private val entries = LinkedHashMap<AccountId, P115Credential>(initial)

    override suspend fun save(accountId: AccountId, credential: P115Credential) {
        entries[accountId] = credential
    }

    override suspend fun load(accountId: AccountId): P115Credential? = entries[accountId]

    override suspend fun delete(accountId: AccountId) {
        entries.remove(accountId)
    }

    override suspend fun listAccountIds(): List<AccountId> = entries.keys.toList()

    /** Test-only inspection helper; deliberately not part of [P115CredentialStore]. */
    fun snapshot(): Map<AccountId, P115Credential> = entries.toMap()
}
